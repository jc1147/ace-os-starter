#!/usr/bin/env node
// build-sitemap.mjs - the memory sitemap (Phase 3). Reads your tree (sitemap/tree.json), the placement
// registry (sitemap/placement.json), the skills list (sitemap/skills.json) and every note (through lib/notes.mjs),
// and writes, atomically:
//   <memory dir>/_sitemap.json     the data contract read by the dashboard's sitemap page and the brain (version 1)
//   <map dir>/_SITEMAP.md          sections, topics, scopes, counts, links to the section maps, inbox and review counts
//   <map dir>/_MOC-<section>.md    one map per section: per topic its scope and its notes, then "Also relevant here"
//                                  and the section's playbooks (skills)
// A note's own metadata.home (and metadata.also) wins over the registry; a note with no valid home goes to the
// inbox ("Needs a home"). Owner text between <!-- @user --> and <!-- @end-user --> in a map survives rebuilds;
// only the <!-- @generated ... --> ... <!-- @end-generated --> block is rewritten. A file that exists but was not
// generated by this tool is never overwritten (exit 1).
// <map dir> = the repo root, or <memory dir>/_mocs-out when the memory dir came from env without MEMSYS_ROOT
// (the same sandbox guard as build-mocs.mjs: fixture data never rewrites the live maps).
// Unchanged output is not rewritten (_sitemap.json keeps its old "built" and only its file time moves), so two
// rebuilds of the same notes are byte-identical.
//   node build-sitemap.mjs            build and write
//   node build-sitemap.mjs --json     print the data to stdout and write nothing
// Exit 0 ok (problems are printed; sitemap-audit.mjs judges them), 1 a write was refused or failed, 2 no input.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolvePaths, loadSitemapInputs, buildModel, renderSitemapMd, renderSectionMd, mergeOwnerBlocks, isGeneratedFile } from './lib/sitemap.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const JSON_ONLY = process.argv.includes('--json');
const P = resolvePaths(HERE);

function atomicWrite(target, text) {
  const tmp = `${target}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, target);
}
const readOr = (p, d = null) => { try { return fs.readFileSync(p, 'utf8'); } catch (_) { return d; } };

let inputs;
try { inputs = loadSitemapInputs(P); }
catch (e) { console.error(`[build-sitemap] cannot read the sitemap data in ${P.dataDir}: ${e.message}`); process.exit(2); }
if (!fs.existsSync(P.MEM)) { console.error(`[build-sitemap] no memory dir: ${P.MEM}`); process.exit(2); }

const { data, problems, warnings } = buildModel({ memDir: P.MEM, inputs });

if (JSON_ONLY) { process.stdout.write(JSON.stringify(data, null, 1) + '\n'); process.exit(0); }

console.log(`[build-sitemap] mode=${P.mode} -> maps to ${P.mapDir}`);
let refused = 0; let wrote = 0; let same = 0;
// 1. _sitemap.json: compare without "built"; identical content keeps the old file (time touched for staleness)
const jsonPath = `${P.MEM}/_sitemap.json`;
const newJson = JSON.stringify(data, null, 1) + '\n';
let keep = false;
const oldRaw = readOr(jsonPath);
if (oldRaw) {
  try { const o = JSON.parse(oldRaw); keep = JSON.stringify({ ...o, built: '' }) === JSON.stringify({ ...data, built: '' }); } catch (_) { keep = false; }
}
if (keep) same++; else { atomicWrite(jsonPath, newJson); wrote++; }
// the file time is at least now and newer than every input, so the regen hook's "tree or registry newer than
// _sitemap.json" check settles (also when an input carries a file time ahead of the clock)
{
  let t = Date.now();
  for (const f of ['tree.json', 'placement.json', 'skills.json']) { try { t = Math.max(t, fs.statSync(`${P.dataDir}/${f}`).mtimeMs + 1); } catch (_) { /* absent */ } }
  try { fs.utimesSync(jsonPath, new Date(t), new Date(t)); } catch (_) { /* best effort */ }
}

// 2. the maps
if (P.mode === 'sandboxed') fs.mkdirSync(P.mapDir, { recursive: true });
const maps = [['_SITEMAP.md', renderSitemapMd(data, inputs.tree)], ...data.sections.map((s) => [`_MOC-${s.slug}.md`, renderSectionMd(data, s)])];
const sizes = [];
for (const [name, gen] of maps) {
  const target = `${P.mapDir}/${name}`;
  const old = readOr(target);
  if (old !== null && !isGeneratedFile(old)) { console.error(`[build-sitemap] REFUSED ${target}: it exists and was not generated by build-sitemap (move it aside first)`); refused++; continue; }
  const text = mergeOwnerBlocks(old, gen);
  if (old === text) same++; else { atomicWrite(target, text); wrote++; }
  sizes.push(`${name} ${Buffer.byteLength(text)}`);
}

const inboxN = data.inbox.length;
const total = data.sections.reduce((a, s) => a + s.count, 0) + inboxN;
console.log(`[build-sitemap] ${data.noteCount} notes: ${total - inboxN} homed in ${data.sections.length} sections, inbox ${inboxN}, needs review ${data.needsReview.length}, skills ${data.skills.length}`);
console.log(`[build-sitemap] files: ${wrote} written, ${same} unchanged, ${refused} refused`);
console.log(`[build-sitemap] bytes: ${sizes.join(', ')}`);
for (const p of problems) console.log(`[build-sitemap] PROBLEM ${p}`);
if (warnings.length) console.log(`[build-sitemap] ${warnings.length} warning(s); run sitemap-audit.mjs for the list`);
process.exit(refused ? 1 : 0);
